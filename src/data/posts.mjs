/** Опубликованные статьи (на будущее фильтр по статусу). */
export function publishedPosts() {
  return POSTS;
}

export function getPost(slug) {
  return POSTS.find((p) => p.slug === slug);
}

/** Похожие статьи: сначала та же категория, потом остальные. */
export function relatedPosts(slug, limit = 2) {
  const current = getPost(slug);
  if (!current) return [];
  const sameCat = POSTS.filter((p) => p.slug !== slug && p.categoryKey === current.categoryKey);
  const rest = POSTS.filter((p) => p.slug !== slug && p.categoryKey !== current.categoryKey);
  return [...sameCat, ...rest].slice(0, limit);
}
